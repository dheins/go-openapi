// buildModel builds the model of a document, with its operations.
func buildModel(t *testing.T, doc string) *ir.Model {
	t.Helper()
	spec, err := loader.LoadBytes([]byte(doc))
	if err != nil {
		t.Fatal(err)
	}
	return ir.Build(spec, ir.Options{Operations: true})
}

const templateDoc = `openapi: 3.1.0
info: {title: t, version: "1"}
paths:
  /pets:
    get:
      operationId: listPets
      responses: {"200": {description: ok, content: {application/json: {schema: {$ref: "#/components/schemas/Kind"}}}}}
components:
  schemas:
    Kind: {type: string, enum: [cat, dog]}
`

// file returns the content of the file named in files.
func file(t *testing.T, files []File, name string) string {
	t.Helper()
	for _, f := range files {
		if f.Name == name {
			return string(f.Content)
		}
	}
	t.Fatalf("no file %s", name)
	return ""
}

func TestTemplates(t *testing.T) {
	m := buildModel(t, templateDoc)
	// A block replaced, using a block of its own and the built-in
	// functions.
	user := fstest.MapFS{"enum.tmpl": {Data: []byte(`
{{define "enum"}}
{{typeDoc .}}
type {{.Name}} {{goType .Base}}
{{template "constants" .}}
// Validate accepts every value. Generated by goapi {{goapiVersion}}.
func (e {{.Name}}) Validate() error { return nil }
{{end}}

{{define "constants"}}
const (
{{- range .Values}}
	{{.Name}} {{$.Name}} = {{.Literal}}
{{- end}}
)
{{end}}
`)}}
	files, err := Models(m, Options{Package: "models", Templates: user})
	if err != nil {
		t.Fatal(err)
	}
	kind := file(t, files, "kind.go")
	for _, want := range []string{"KindCat Kind = \"cat\"", "func (e Kind) Validate() error { return nil }", "Generated by goapi "} {
		if !strings.Contains(kind, want) {
			t.Errorf("kind.go lacks %q:\n%s", want, kind)
		}
	}
	// The others are the built-in ones.
	plain, err := Models(m, Options{Package: "models"})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(file(t, plain, "kind.go"), "every value") {
		t.Error("the override applies without Templates")
	}

	// A server's handler, as the built-in one with a line added.
	src, err := templateFiles.ReadFile("templates/server.go.tmpl")
	if err != nil {
		t.Fatal(err)
	}
	_, handler, _ := strings.Cut(string(src), `{{define "handler"}}`)
	handler = strings.Replace(`{{define "handler"}}`+handler, "return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {",
		"return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {\n\t\tw.Header().Set(\"X-Generated\", \"custom\")", 1)
	files, err = Server(m, Options{Package: "gen", Templates: fstest.MapFS{"handler.tmpl": {Data: []byte(handler)}}})
	if err != nil {
		t.Fatal(err)
	}
	if h := file(t, files, "list_pets_handler.go"); !strings.Contains(h, `w.Header().Set("X-Generated", "custom")`) {
		t.Errorf("handler:\n%s", h)
	}
}

func TestTemplateErrors(t *testing.T) {
	m := buildModel(t, templateDoc)
	for name, tc := range map[string]struct {
		files fstest.MapFS
		want  string
	}{
		"misspelt": {fstest.MapFS{"a.tmpl": {Data: []byte(`{{define "strcut"}}x{{end}}`)}},
			`a.tmpl defines "strcut", which is neither a block of goapi's templates nor used by another of yours`},
		"outside": {fstest.MapFS{"a.tmpl": {Data: []byte(`stray {{define "enum"}}x{{end}}`)}},
			"a.tmpl has text outside {{define}}"},
		"parse": {fstest.MapFS{"a.tmpl": {Data: []byte("{{define \"enum\"}}\n{{.Name}\n{{end}}")}},
			"a.tmpl:2"},
		"function": {fstest.MapFS{"a.tmpl": {Data: []byte(`{{define "enum"}}{{nope .}}{{end}}`)}},
			`function "nope" not defined`},
		"execute": {fstest.MapFS{"a.tmpl": {Data: []byte(`{{define "enum"}}{{.Nope}}{{end}}`)}},
			"can't evaluate field Nope"},
		"empty": {fstest.MapFS{"readme.md": {Data: []byte("x")}},
			"no *.tmpl files"},
	} {
		_, err := Models(m, Options{Package: "models", Templates: tc.files})
		if err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Errorf("%s: %v, want %q", name, err, tc.want)
		}
	}
}

func TestTSTemplates(t *testing.T) {
	src, err := os.ReadFile("testdata/golden/petserver/openapi.yaml")
	if err != nil {
		t.Fatal(err)
	}
	m := buildModel(t, string(src))
	// Interfaces as type aliases, methods with a tag, and the index with
	// a block of its own.
	user := fstest.MapFS{
		"client.tmpl": {Data: []byte(`
{{define "interface"}}export type {{name .}} = {{template "object" .}};{{end}}

{{define "method"}}
{{tsDoc "  " (print (operationDoc .Operation) "\n\n@generated") .Operation.Deprecated}}  {{.Method}}(req: {{.Operation.RequestType}}{{if .Optional}} = {}{{end}}, call?: CallOptions): Promise<{{.Operation.ResponseType}}> {
    return send(this.#cfg, {{.Method}}Spec, req, call) as Promise<{{.Operation.ResponseType}}>;
  }
{{end}}
`)},
		"index.tmpl": {Data: []byte(`{{define "index"}}export * as models from "./models.ts";
{{template "exports" .}}{{end}}

{{define "exports"}}export { {{join .Names ", "}} } from "./runtime.ts";
export * as runtime from "./runtime.ts";
export * from "./models.ts";
{{if .Client}}export * from "./client.ts";
{{end}}{{end}}`)},
	}
	files, _, err := TypeScript(m, TSOptions{Templates: user})
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	for _, f := range files {
		if err := os.WriteFile(filepath.Join(dir, f.Name), f.Content, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	for name, want := range map[string]string{
		"models.ts": "export type Pet = {",
		"client.ts": "   * @generated\n   */\n  listPets(",
		"index.ts":  "export * as models from \"./models.ts\";\nexport {",
	} {
		if got := file(t, files, name); !strings.Contains(got, want) {
			t.Errorf("%s lacks %q", name, want)
		}
	}
	if strings.Contains(file(t, files, "models.ts"), "export interface") {
		t.Error("models.ts has interfaces")
	}

	if _, _, err := TypeScript(m, TSOptions{Templates: fstest.MapFS{"a.tmpl": {Data: []byte(`{{define "mehtod"}}{{end}}`)}}}); err == nil ||
		!strings.Contains(err.Error(), `"mehtod"`) || !strings.Contains(err.Error(), "linkMethod") {
		t.Errorf("misspelt: %v", err)
	}

	if testing.Short() {
		return
	}
	tsc := tscCommand(t)
	generated, _ := tsFiles(t, dir)
	if out, err := exec.Command(tsc[0], append(append(tsc[1:], tscFlags...), generated...)...).CombinedOutput(); err != nil {
		t.Errorf("tsc: %v\n%s", err, out)
	}
}

// TestBuiltinTemplates checks that the built-in templates, given as user
// ones, as goapi templates writes them, generate what they do anyway.
func TestBuiltinTemplates(t *testing.T) {
	src, err := os.ReadFile("testdata/golden/petserver/openapi.yaml")
	if err != nil {
		t.Fatal(err)
	}
	m := buildModel(t, string(src))
	same := func(what string, want, got []File) {
		t.Helper()
		if len(want) != len(got) {
			t.Fatalf("%s: %d files, want %d", what, len(got), len(want))
		}
		for i := range want {
			if want[i].Name != got[i].Name || string(want[i].Content) != string(got[i].Content) {
				t.Errorf("%s: %s differs", what, want[i].Name)
			}
		}
	}
	for name, gen := range map[string]func(*ir.Model, Options) ([]File, error){"models": Models, "server": Server, "client": Client} {
		opts := Options{Package: "gen", OperationsPackage: "api", OperationsImport: "example.com/gen/api", ModelsPackage: "model", ModelsImport: "example.com/gen/model"}
		want, err := gen(m, opts)
		if err != nil {
			t.Fatal(err)
		}
		opts.Templates = GoTemplates()
		got, err := gen(m, opts)
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		same(name, want, got)
	}
	want, _, err := TypeScript(m, TSOptions{})
	if err != nil {
		t.Fatal(err)
	}
	got, _, err := TypeScript(m, TSOptions{Templates: TSTemplates()})
	if err != nil {
		t.Fatal(err)
	}
	same("typescript", want, got)
}
